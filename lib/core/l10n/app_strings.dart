  /// Every key in one language has a translation in the other (used by tests).
  static Set<String> keys(String languageCode) => _values[languageCode]!.keys.toSet();
}

extension AppStringsContext on BuildContext {
  /// Translated string for [key], with `{name}` placeholders filled from [args].
  String tr(String key, [Map<String, Object?> args = const {}]) {
    final code = Localizations.maybeLocaleOf(this)?.languageCode ?? 'en';
    var value = AppStrings.of(code, key);
    args.forEach((k, v) => value = value.replaceAll('{$k}', '$v'));
    return value;
  }
}
